// +10 per correct vote across resolved polls (HANDOFF §13.3).
export function computeLeaderboard(polls, votes, members) {
  const pts = {};
  for (const p of polls) {
    if (p.status !== 'resolved') continue;
    for (const v of votes) {
      if (v.poll_id === p.id && v.option_id === p.correct_option_id) pts[v.user_id] = (pts[v.user_id] ?? 0) + 10;
    }
  }
  return members
    .filter((m) => m.status === 'joined' || pts[m.user_id])
    .map((m) => ({ member: m, pts: pts[m.user_id] ?? 0 }))
    .sort((a, b) => b.pts - a.pts || (a.member.profile?.display_name ?? '').localeCompare(b.member.profile?.display_name ?? ''));
}

export function Leaderboard({ rows, config, meId }) {
  return (
    <ol className="leader-list">
      {rows.map((r, i) => {
        const look = memberLook(r.member, config);
        return (
          <li key={r.member.user_id} className={`leader ${r.member.user_id === meId ? 'me' : ''}`}>
            <span className={`rank ${i === 0 && r.pts > 0 ? 'top' : ''}`}>{i + 1}</span>
            <Avatar name={look.name} ring={look.ring} size={28} />
            <span className="nm">{look.name}{r.member.user_id === meId ? ' (you)' : ''}</span>
            <span className="pts">{r.pts}</span>
            <span className="u">pts</span>
          </li>
        );
      })}
    </ol>
  );
}

function PollCard({ poll, position, config }) {
  const { user } = useAuth();
  const { votes, memberMap, vote } = useParty();
  const pollVotes = votes.filter((v) => v.poll_id === poll.id);
  const mine = pollVotes.find((v) => v.user_id === user.id)?.option_id;
  const resolved = poll.status === 'resolved';
  const votingOpen = !resolved && position < poll.votes_close_at_video_time;
  const total = pollVotes.length;

  let timer;
  let timerCls = '';
  if (resolved) { timer = 'Resolved'; timerCls = 'closed'; }
  else if (votingOpen) {
    const rem = Math.max(0, Math.ceil(poll.votes_close_at_video_time - position));
    timer = `Voting closes in ${Math.floor(rem / 60)}:${String(rem % 60).padStart(2, '0')}`;
    if (rem < 30) timerCls = 'soon';
  } else {
    timer = `Result at ${videoToMatchClock(config, poll.closes_at_video_time).minute}`;
    timerCls = 'closed';
  }

  const winners = resolved
    ? pollVotes.filter((v) => v.option_id === poll.correct_option_id).map((v) => memberMap[v.user_id]?.profile?.display_name).filter(Boolean)
    : [];

  return (
    <section className={`poll ${resolved ? 'resolved' : ''} ${resolved && mine && mine === poll.correct_option_id ? 'won' : ''}`} aria-label={resolved ? 'Resolved poll' : 'Current poll'}>
      <div className="poll-head">
        <span className="gen-tag"><GafferIcon size={12} />{poll.created_by === 'gaffer' ? 'Generated by Gaffer' : 'Poll by a guest, written by Gaffer'}</span>
        <span className={`poll-timer ${timerCls}`}><Timer size={12} strokeWidth={2.4} aria-hidden="true" />{timer}</span>
      </div>
      <h3 className="poll-q">{poll.question}</h3>
      <div className="poll-opts">
        {poll.options.map((o) => {
          const vs = pollVotes.filter((v) => v.option_id === o.id);
          const pct = total ? Math.round((vs.length / total) * 100) : 0;
          const isMine = mine === o.id;
          const correct = resolved && poll.correct_option_id === o.id;
          return (
            <button
              key={o.id}
              type="button"
              className={`poll-opt ${isMine ? 'mine' : ''} ${correct ? 'correct' : ''}`}
              aria-pressed={isMine}
              disabled={!votingOpen || !!mine}
              onClick={() => vote(poll.id, o.id)}
            >
              <span className="fill" style={{ width: `${pct}%` }} aria-hidden="true" />
              <span className="radio">{isMine && <Check size={10} strokeWidth={4} aria-hidden="true" />}</span>
              <span className="lbl">{o.label}</span>
              {correct && <span className="correct-tag">Correct</span>}
              <span className="voters" aria-hidden="true">
                {vs.slice(0, 4).map((v) => {
                  const look = memberLook(memberMap[v.user_id], config);
                  return <Avatar key={v.user_id} name={look.name} ring={look.ring} size={22} />;
                })}
              </span>
              <span className="pct">{pct}%</span>
            </button>
          );
        })}
      </div>
      {resolved ? (
        <span className="poll-right">{winners.length ? `✓ ${winners.join(', ')} got it right` : 'Nobody got this one right'}</span>
      ) : (
        <span className="poll-foot">{total} {total === 1 ? 'vote' : 'votes'}{mine ? ' · You voted' : votingOpen ? '' : ' · Voting closed'}</span>
      )}
    </section>
  );
}

export default function PollsTab({ match, position }) {
  const { user } = useAuth();
  const { party, polls, votes, members, isHost } = useParty();
  const toast = useToast();
  const [busy, setBusy] = useState(false);
  const config = match.config;
  const visible = polls.filter((p) => p.status !== 'void');
  const open = visible.filter((p) => p.status === 'open');
  const resolved = visible.filter((p) => p.status === 'resolved').reverse();
  const canCreate = (isHost || party?.settings?.guests_can_poll) && party?.status === 'live';

  const generate = async () => {
    setBusy(true);
    const { error } = await supabase.functions.invoke('generate-poll', { body: { party_id: party.id } });
    setBusy(false);
    if (!error) return;
    const status = invokeStatus(error);
    toast(status === 409 ? 'A poll is already open' : status === 429 ? 'Gaffer just made one — try again in a minute' : status === 400 ? 'No more polls — the match is over' : "Gaffer couldn't make a poll right now", 'warn');
  };

  return (
    <div className="tab-body scroll">
      <div className="tab-pad">
        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', gap: 10 }}>
          <h2 className="tab-h">Predictions</h2>
          {canCreate && (
            <button type="button" className="btn btn-sm btn-soft" onClick={generate} disabled={busy || open.length > 0}>
              {busy ? <Spinner /> : <GafferIcon size={14} />}Ask Gaffer for a poll
            </button>
          )}
        </div>
        {visible.length === 0 && (
          <p style={{ margin: 0, fontSize: 13, color: 'var(--muted-3)', lineHeight: 1.5 }}>
            Gaffer drops a prediction poll every few minutes of match time. Polls are settled from the match data, then the leaderboard updates.
          </p>
        )}
        {open.map((p) => <PollCard key={p.id} poll={p} position={position} config={config} />)}
        {resolved.map((p) => <PollCard key={p.id} poll={p} position={position} config={config} />)}
        <section aria-labelledby="lb-h" className="card card-pad" style={{ display: 'flex', flexDirection: 'column', gap: 10, padding: 14 }}>
          <h3 id="lb-h" className="sub-h">Prediction leaderboard</h3>
          <Leaderboard rows={computeLeaderboard(polls, votes, members)} config={config} meId={user.id} />
        </section>
      </div>
    </div>
  );
}
